/**
 * The multiplier VADER applies to a valence sitting within three words after a
 * negation. Negative rather than zero because "not great" is mildly negative,
 * not neutral, and it is weaker than +1 because negation softens.
 */
export const NEGATION_SCALAR = -0.74;

let merged: Map<string, number> | null = null;

/** The base lexicon with the review-specific terms layered over the top. */
export function reviewLexicon(): Map<string, number> {
  if (merged) return merged;
  const map = new Map(baseLexicon());
  for (const [word, value] of Object.entries(REVIEW_TERMS)) {
    map.set(word, value);
  }
  merged = map;
  return merged;
}

export function reviewPhrases(): Array<[string, number]> {
  return Object.entries(REVIEW_PHRASES);
}
